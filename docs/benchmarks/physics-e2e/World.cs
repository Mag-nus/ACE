/// <summary>
/// Builds a synthetic outdoor world that the REAL server physics code runs against, with
/// PhysicsEngine.Instance.Server == true:
///   - real ACE.Server.Physics.Common.Landblock objects built by the real constructors from
///     CellLandblock records parsed by the real DatLoader Unpack from generated bytes;
///   - registered in the REAL LandblockManager.landblocks table (wrapped in uninitialised
///     ACE.Server.Entity.Landblock shells whose only populated member is PhysicsLandblock), so
///     LScape.get_landblock runs its production body including LandblockManager.GetLandblock
///     and its ReaderWriterLockSlim;
///   - DatManager.PortalDat is an uninitialised PortalDatDatabase whose FileCache is pre-seeded
///     with SetupModel / Animation / MotionTable records parsed by the real Unpack from
///     generated bytes, so Setup.Get / DBObj.GetSetup / DBObj.GetAnimation run unmodified.
/// </summary>
public static class World
{
    public const float HStep = 0.25f;          // LandHeightTable[i] = i * HStep metres
    public static Action<double> SetTime;
    public static double Time { get => Timers.PortalYearTicks; set => SetTime(value); }

    static SLandblock[,] slots;
    static FieldInfo physLbField;
    public static ConcurrentDictionary<uint, FileType> PortalCache;
    static bool inited;

    public static void Init()
    {
        if (inited) return;
        inited = true;

        // PhysicsEngine.Instance.Server = true without running its ctor (no ObjectMaint / SmartBox needed;
        // the only member of PhysicsEngine the server physics path reads is .Server).
        var pe = (PhysicsEngine)RuntimeHelpers.GetUninitializedObject(typeof(PhysicsEngine));
        pe.Server = true;
        PhysicsEngine.Instance = pe;

        // LandDefs' static ctor reads the height table from the portal dat when one is loaded; run it now, while there is none.
        var t = new List<float>(256);
        for (int i = 0; i < 256; i++) t.Add(i * HStep);
        LandDefs.LandHeightTable = t;

        PLandblock.UseSceneFiles = false;      // scenery generation needs RegionDesc from the portal dat

        SetTime = (Action<double>)typeof(Timers).GetProperty("PortalYearTicks").GetSetMethod(true).CreateDelegate(typeof(Action<double>));
        Time = 1000.0;

        slots = (SLandblock[,])typeof(LandblockManager).GetField("landblocks", BindingFlags.NonPublic | BindingFlags.Static).GetValue(null);
        physLbField = typeof(SLandblock).GetField("<PhysicsLandblock>k__BackingField", BindingFlags.NonPublic | BindingFlags.Instance);
        if (slots == null || physLbField == null) throw new Exception("LandblockManager reflection failed");

        // stub portal dat: uninitialised object with a live FileCache
        var portal = (PortalDatDatabase)RuntimeHelpers.GetUninitializedObject(typeof(PortalDatDatabase));
        PortalCache = new ConcurrentDictionary<uint, FileType>();
        SetBacking(portal, typeof(DatDatabase), "FileCache", PortalCache);
        SetBacking(portal, typeof(DatDatabase), "AllFiles", new Dictionary<uint, DatFile>());
        typeof(DatManager).GetProperty("PortalDat").GetSetMethod(true).Invoke(null, new object[] { portal });
    }

    public static void SetBacking(object o, Type t, string prop, object value)
    {
        var f = t.GetField($"<{prop}>k__BackingField", BindingFlags.Instance | BindingFlags.NonPublic);
        if (f == null) throw new Exception("no backing field " + prop + " on " + t);
        f.SetValue(o, value);
    }

    public delegate float HeightFn(float gx, float gy);

    public sealed class Region
    {
        public int Bx0, By0, Nx, Ny;
        public HeightFn H;
        public uint BlockId(int ix, int iy) => (uint)(((Bx0 + ix) << 24) | ((By0 + iy) << 16) | 0xFFFF);
        /// world metres (relative to the region's SW corner) -> (cell id, landblock-local origin on the terrain surface + zAbove)
        public (uint cell, Vector3 origin) At(float gx, float gy, float zAbove = 0.005f)
        {
            int ix = (int)MathF.Floor(gx / 192f), iy = (int)MathF.Floor(gy / 192f);
            float lx = gx - ix * 192f, ly = gy - iy * 192f;
            int cx = Math.Min(7, (int)(lx / 24f)), cy = Math.Min(7, (int)(ly / 24f));
            uint cell = (BlockId(ix, iy) & 0xFFFF0000) | (uint)(cx * 8 + cy + 1);
            var plb = LScape.get_landblock(cell);
            float z = plb.GetZ(new Vector3(lx, ly, 0));
            return (cell, new Vector3(lx, ly, z + zAbove));
        }
        public float SizeX => Nx * 192f;
        public float SizeY => Ny * 192f;
    }

    /// <summary>Builds nx * ny landblocks at block coords (bx0, by0). Terrain type 0 everywhere (no water, no roads).</summary>
    public static Region Build(int bx0, int by0, int nx, int ny, HeightFn h)
    {
        Init();
        var region = new Region { Bx0 = bx0, By0 = by0, Nx = nx, Ny = ny, H = h };
        var shells = new SLandblock[nx, ny];
        for (int ix = 0; ix < nx; ix++)
            for (int iy = 0; iy < ny; iy++)
            {
                uint id = region.BlockId(ix, iy);
                var ms = new MemoryStream();
                var w = new BinaryWriter(ms);
                w.Write(id); w.Write(0u);                       // Id, hasObjects = 0 (no LandblockInfo)
                for (int i = 0; i < 81; i++) w.Write((ushort)0);  // terrain: type 0, no road, no scenery
                for (int vx = 0; vx < 9; vx++)
                    for (int vy = 0; vy < 9; vy++)
                    {
                        float z = h(ix * 192f + vx * 24f, iy * 192f + vy * 24f);
                        w.Write((byte)Math.Clamp((int)MathF.Round(z / HStep), 0, 255));
                    }
                while (ms.Position % 4 != 0) w.Write((byte)0);
                var clb = new CellLandblock();
                ms.Position = 0;
                using (var r = new BinaryReader(ms)) clb.Unpack(r);   // real parser

                var plb = new PLandblock(clb);    // real ctor: LandblockStruct.Generate, ConstructVertices, ConstructPolygons, CalcWater
                plb.PostInit();                   // real: init_landcell (+ no buildings / static objects without LandblockInfo)

                var shell = (SLandblock)RuntimeHelpers.GetUninitializedObject(typeof(SLandblock));
                physLbField.SetValue(shell, plb);
                shells[ix, iy] = shell;
                if (slots[bx0 + ix, by0 + iy] != null) throw new Exception("landblock slot already used");
                slots[bx0 + ix, by0 + iy] = shell;
            }
        // adjacency, as LandblockManager.SetAdjacents would cache it (needed by ObjectMaint.GetVisibleObjects -> GetServerObjects(true))
        for (int ix = 0; ix < nx; ix++)
            for (int iy = 0; iy < ny; iy++)
            {
                var adj = new List<SLandblock>();
                for (int dx = -1; dx <= 1; dx++)
                    for (int dy = -1; dy <= 1; dy++)
                    {
                        if (dx == 0 && dy == 0) continue;
                        int ax = ix + dx, ay = iy + dy;
                        if (ax < 0 || ay < 0 || ax >= nx || ay >= ny) continue;
                        adj.Add(shells[ax, ay]);
                    }
                shells[ix, iy].PhysicsLandblock.SetAdjacents(adj);
            }
        return region;
    }

    // ------------------------------------------------------------------ synthetic dat records

    static void Vec(BinaryWriter w, Vector3 v) { w.Write(v.X); w.Write(v.Y); w.Write(v.Z); }

    public sealed class SetupSpec
    {
        public uint Id;
        public int Parts = 17;
        public bool AllowFreeHeading = false;
        public (Vector3 c, float r)[] Spheres = Array.Empty<(Vector3, float)>();
        public (Vector3 low, float r, float h)[] CylSpheres = Array.Empty<(Vector3, float, float)>();
        public float Height = 1.8f, Radius = 0.4f, StepUp = 0.6f, StepDown = 0.6f;
        public uint DefaultMotionTable = 0;
    }

    /// <summary>Generates a Setup (0x02) record in dat layout, parses it with the real SetupModel.Unpack and seeds the portal FileCache.</summary>
    public static SetupModel SeedSetup(SetupSpec s)
    {
        Init();
        var ms = new MemoryStream();
        var w = new BinaryWriter(ms);
        w.Write(s.Id);
        w.Write((uint)(s.AllowFreeHeading ? SetupFlags.AllowFreeHeading : 0));
        w.Write((uint)s.Parts);
        for (int i = 0; i < s.Parts; i++)
        {
            uint gid = 0x01000100u + (uint)i;
            w.Write(gid);
            GfxObjCache.GfxObjs.TryAdd(gid, new ACE.Server.Physics.Collision.GfxObj { ID = gid });   // parts without physics BSP (as creature parts); no dat access
        }
        w.Write(0);                     // HoldingLocations
        w.Write(0);                     // ConnectionPoints
        w.Write(1);                     // placements
        w.Write(0x65);                  // Placement.Resting
        for (int i = 0; i < s.Parts; i++)
        {
            Vec(w, new Vector3(0, 0, 0.1f * i));
            w.Write(1f); w.Write(0f); w.Write(0f); w.Write(0f);   // qw qx qy qz
        }
        w.Write(0u);                    // hooks
        w.Write((uint)s.CylSpheres.Length);
        foreach (var c in s.CylSpheres) { Vec(w, c.low); w.Write(c.r); w.Write(c.h); }
        w.Write((uint)s.Spheres.Length);
        foreach (var sp in s.Spheres) { Vec(w, sp.c); w.Write(sp.r); }
        w.Write(s.Height); w.Write(s.Radius); w.Write(s.StepUp); w.Write(s.StepDown);
        Vec(w, new Vector3(0, 0, s.Height * 0.5f)); w.Write(s.Height * 0.6f);    // sorting sphere
        Vec(w, new Vector3(0, 0, s.Height * 0.5f)); w.Write(s.Height * 0.6f);    // selection sphere
        w.Write(0);                     // lights
        w.Write(0u); w.Write(0u); w.Write(s.DefaultMotionTable); w.Write(0u); w.Write(0u);
        var model = new SetupModel();
        ms.Position = 0;
        using (var r = new BinaryReader(ms))
        {
            model.Unpack(r);
            if (r.BaseStream.Position != r.BaseStream.Length) throw new Exception("setup unpack size mismatch");
        }
        PortalCache[s.Id] = model;
        return model;
    }

    /// <summary>Generates an Animation (0x03) record: numFrames part-frames, optional pos-frames, no hooks.</summary>
    public static ACE.DatLoader.FileTypes.Animation SeedAnimation(uint id, int numParts, int numFrames, bool posFrames)
    {
        Init();
        var ms = new MemoryStream();
        var w = new BinaryWriter(ms);
        w.Write(id);
        w.Write(posFrames ? 1u : 0u);      // AnimationFlags.PosFrames = 1
        w.Write((uint)numParts);
        w.Write((uint)numFrames);
        if (posFrames)
            for (int f = 0; f < numFrames; f++) { Vec(w, Vector3.Zero); w.Write(1f); w.Write(0f); w.Write(0f); w.Write(0f); }
        for (int f = 0; f < numFrames; f++)
        {
            for (int p = 0; p < numParts; p++) { Vec(w, new Vector3(0, 0, 0.1f * p)); w.Write(1f); w.Write(0f); w.Write(0f); w.Write(0f); }
            w.Write(0u);                // hooks
        }
        var anim = new ACE.DatLoader.FileTypes.Animation();
        ms.Position = 0;
        using (var r = new BinaryReader(ms))
        {
            anim.Unpack(r);
            if (r.BaseStream.Position != r.BaseStream.Length) throw new Exception("anim unpack size mismatch");
        }
        PortalCache[id] = anim;
        return anim;
    }
}

public sealed class StubWO : WorldObject { }

/// <summary>Object factories mirroring WorldObject.InitPhysicsObj / AddPhysicsObj call for call.</summary>
public static class Objects
{
    static uint nextGuid = 0x80000100;
    static readonly FieldInfo fIsCreature = typeof(WeenieObject).GetField("IsCreature");
    static readonly FieldInfo fIsMonster = typeof(WeenieObject).GetField("IsMonster");
    static readonly MethodInfo setPhysicsObj = typeof(WorldObject).GetProperty("PhysicsObj").GetSetMethod(true);
    public static readonly List<WorldObject> KeepAlive = new();   // WeenieObject only holds a WeakReference

    public static WorldObject MakeWO(uint guid, uint cell, Vector3 origin, Quaternion rot)
    {
        var wo = new StubWO();   // real parameterless WorldObject ctor (field initialisers run)
        var biota = new Biota { Id = guid, WeenieClassId = 1, WeenieType = WeenieType.Generic };
        biota.PropertiesInt = new Dictionary<ACE.Entity.Enum.Properties.PropertyInt, int>();
        biota.PropertiesPosition = new Dictionary<ACE.Entity.Enum.Properties.PositionType, PropertiesPosition>();
        biota.PropertiesString = new Dictionary<ACE.Entity.Enum.Properties.PropertyString, string>();
        biota.PropertiesBool = new Dictionary<ACE.Entity.Enum.Properties.PropertyBool, bool>();
        biota.PropertiesFloat = new Dictionary<ACE.Entity.Enum.Properties.PropertyFloat, double>();
        biota.PropertiesDID = new Dictionary<ACE.Entity.Enum.Properties.PropertyDataId, uint>();
        biota.PropertiesIID = new Dictionary<ACE.Entity.Enum.Properties.PropertyInstanceId, uint>();
        World.SetBacking(wo, typeof(WorldObject), "Biota", biota);
        World.SetBacking(wo, typeof(WorldObject), "Guid", new ObjectGuid(guid));
        wo.Location = new ACE.Entity.Position(cell, origin, rot);
        KeepAlive.Add(wo);
        return wo;
    }

    /// <summary>
    /// InitPhysicsObj, creature branch: new PhysicsObj(); makeAnimObject(setup, true); set_object_guid; set_weenie_obj(new WeenieObject(wo));
    /// SetMotionTableID(mtable); SetScaleStatic(1); State = defaultState.
    /// creature == false uses the non-creature branch: PhysicsObj.makeObject(setup, guid, dynamic).
    /// </summary>
    public static PhysicsObj Make(uint setupId, PhysicsState state, bool creature, bool monster, uint mtable = 0, bool movementManager = false, uint? guidOverride = null)
    {
        uint guid = guidOverride ?? nextGuid++;
        var wo = MakeWO(guid, 0, Vector3.Zero, Quaternion.Identity);
        PhysicsObj po;
        if (creature)
        {
            po = new PhysicsObj();
            po.makeAnimObject(setupId, true);
        }
        else
            po = PhysicsObj.makeObject(setupId, guid, true);

        po.set_object_guid(wo.Guid);
        var weenie = new WeenieObject(wo);                 // real ctor; a StubWO is not a Creature, so flag the two readonly bools by reflection
        if (creature) fIsCreature.SetValue(weenie, true);
        if (monster) fIsMonster.SetValue(weenie, true);
        po.set_weenie_obj(weenie);
        po.SetMotionTableID(mtable);                       // with mtable != 0 this also does MakeMovementManager(true)
        if (mtable == 0 && movementManager)
            po.MakeMovementManager(true);                  // what SetMotionTableID does for any creature that has a motion table
        po.SetScaleStatic(1.0f);
        po.State = state;
        setPhysicsObj.Invoke(wo, new object[] { po });
        return po;
    }

    /// <summary>AddPhysicsObj: get_landcell, Position.ObjCellID = cell.ID, enter_world(location).</summary>
    public static bool Place(PhysicsObj po, uint cellId, Vector3 origin, Quaternion rot)
    {
        var wo = po.WeenieObj.WorldObject;
        wo.Location = new ACE.Entity.Position(cellId, origin, rot);
        var cell = LScape.get_landcell(cellId);
        if (cell == null) return false;
        po.Position.ObjCellID = cell.ID;
        var location = new PPosition();
        location.ObjCellID = cell.ID;
        location.Frame.Origin = origin;
        location.Frame.Orientation = rot;
        var success = po.enter_world(location);
        if (!success || po.CurCell == null) return false;
        wo.SyncLocation();
        return true;
    }

    public static bool Place(PhysicsObj po, World.Region r, float gx, float gy, float headingDeg = 0, float zAbove = 0.005f)
    {
        var (cell, origin) = r.At(gx, gy, zAbove);
        var f = new AFrame(); f.set_heading(headingDeg);
        return Place(po, cell, origin, f.Orientation);
    }

    public static void Remove(PhysicsObj po)
    {
        po.DestroyObject();
        ACE.Server.Physics.Managers.ServerObjectManager.RemoveServerObject(po);
    }
}
